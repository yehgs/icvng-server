export function chatStrings(language = "en") {
  const l = S[language] || {};
  return { ...S.en, ...l, roles: { ...S.en.roles, ...(l.roles || {}) } };
}

export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}
